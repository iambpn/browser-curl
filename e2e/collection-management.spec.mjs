/** Organize saved requests through the real collections panel and extension storage. */
import {appendFile} from 'node:fs/promises'
import {test, expect} from './fixtures.mjs'
import {click, fill, expectHidden, expectText, expectValue, savedWorkspaceWith, storedCollections, storedWorkspace} from './panel-helpers.mjs'

async function proof(panel, name) {
  if (process.env.FACTORY_EVIDENCE !== '1') return
  await panel.screenshot({path: `.factory-evidence/${name}.png`})
  await appendFile('.factory-evidence/captures.jsonl', JSON.stringify({name, video: await panel.video().path()}) + '\n')
}

function row(panel, name) {
  return panel.locator('.collection-row').filter({has: panel.locator('[data-item-name]', {hasText: new RegExp(`^${name}$`)})})
}

async function create(panel, name, parent) {
  if (parent) await row(panel, parent).getByRole('button', {name: 'Add folder', exact: true}).click()
  else await panel.getByRole('button', {name: 'New collection', exact: true}).click()
  await fill(panel, '#collection-item-name', name)
  await click(panel, '#confirm-collection-item')
  await expectHidden(panel, '#collection-item-form')
  await expect(row(panel, name)).toBeVisible()
}

async function saveIn(panel, name, destination, evidenceName) {
  await click(panel, '#save-as')
  await fill(panel, '#save-request-name', name)
  await panel.locator('#save-collection').selectOption({label: destination})
  await proof(panel, evidenceName ?? (destination.startsWith('\u00a0'.repeat(4)) ? 'nested-folder-save-picker' : 'folder-save-picker'))
  await click(panel, '#confirm-save-as')
  await expectHidden(panel, '#save-as-dialog')
}

test('creates nested folders, saves inside them, preserves order and depth after restart, and expands and collapses', async ({extension, api}) => {
  let panel = await extension.openPanel()
  await click(panel, '#show-collections')
  await expect(panel.locator('#collections-empty')).toContainText('New collection')
  await proof(panel, 'new-collection-empty-panel')
  await create(panel, 'API')
  await create(panel, 'Outer', 'API')
  await create(panel, 'Inner', 'Outer')
  await click(panel, '#close-collections')
  await fill(panel, '#request-url', `${api.origin}/echo`)
  await saveIn(panel, 'Nested request', '\u00a0\u00a0\u00a0\u00a0Inner')
  await saveIn(panel, 'Root request', 'API')
  await saveIn(panel, 'Outer request', '\u00a0\u00a0Outer')
  await click(panel, '#show-collections')
  await create(panel, 'Last folder', 'API')
  await click(panel, '#close-collections')
  await saveIn(panel, 'Last request', 'API')
  await extension.restart()
  panel = await extension.openPanel()
  await click(panel, '#show-collections')
  await panel.setViewportSize({width: 380, height: 820})
  await expect(panel.locator('[data-item-name]')).toHaveText(['API', 'Outer', 'Inner', 'Nested request', 'Outer request', 'Root request', 'Last folder', 'Last request'])
  const positions = await panel.locator('[data-item-name]').evaluateAll(nodes => nodes.map(node => node.getBoundingClientRect().left))
  expect(positions[1]).toBeGreaterThan(positions[0])
  expect(positions[2]).toBeGreaterThan(positions[1])
  expect(positions[3]).toBeGreaterThan(positions[2])
  await proof(panel, 'nested-folders-after-restart')
  await panel.emulateMedia({colorScheme: 'dark'})
  await proof(panel, 'nested-folders-dark-mode')
  await panel.emulateMedia({colorScheme: 'light'})
  for (const name of ['Inner', 'Outer', 'API']) {
    const toggle = row(panel, name).getByRole('button', {name: `Collapse ${name}`, exact: true})
    await toggle.click()
    await expect(row(panel, 'Nested request')).toBeHidden()
    await proof(panel, `collapsed-${name.toLowerCase()}`)
    await row(panel, name).getByRole('button', {name: `Expand ${name}`, exact: true}).click()
    await expect(row(panel, 'Nested request')).toBeVisible()
  }
  await row(panel, 'Nested request').locator('[data-open-collection-request]').click()
  await expectHidden(panel, '#collections-dialog')
  await expectValue(panel, '#request-url', `${api.origin}/echo`)
})

async function rename(panel, oldName, newName, key = 'Enter') {
  await row(panel, oldName).getByRole('button', {name: 'Rename', exact: true}).click()
  const input = row(panel, oldName).getByRole('textbox', {name: 'Name'})
  await input.fill(newName)
  await proof(panel, 'inline-name-editing')
  await input.press(key)
}

test('renames collections, folders and requests inline, rejects empty names, and cancels with Escape', async ({extension, api}) => {
  const panel = await extension.openPanel()
  await click(panel, '#show-collections')
  await create(panel, 'API')
  await create(panel, 'Folder', 'API')
  await click(panel, '#close-collections')
  await fill(panel, '#request-url', `${api.origin}/echo`)
  await saveIn(panel, 'Request', '\u00a0\u00a0Folder')
  await click(panel, '#show-collections')
  for (const [oldName, newName] of [['API', 'Renamed API'], ['Folder', 'Renamed folder'], ['Request', 'Renamed request']]) {
    await rename(panel, oldName, newName)
    await expect(row(panel, newName)).toBeVisible()
    for (const empty of ['', '   ']) {
      await rename(panel, newName, empty)
      await expect(row(panel, newName)).toBeVisible()
      await expect(panel.locator('#collections-error')).toHaveText('Enter a name.')
    }
    await proof(panel, `empty-name-rejected-${oldName.toLowerCase()}`)
    await rename(panel, newName, 'Cancelled name', 'Escape')
    await expect(row(panel, newName)).toBeVisible()
  }
  await proof(panel, 'inline-renames-and-empty-name-rejected')
  await extension.restart()
  const restored = await extension.openPanel()
  await click(restored, '#show-collections')
  await expect(restored.locator('[data-item-name]')).toHaveText(['Renamed API', 'Renamed folder', 'Renamed request'])
})

