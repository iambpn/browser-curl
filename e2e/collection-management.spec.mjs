test('deletes requests immediately, confirms recursive deletion, and deletes empty containers without confirmation', async ({extension, api}) => {
  const panel = await extension.openPanel()
  panel.on('dialog', () => { throw new Error('Browser dialogs must never be used for collections') })
  await click(panel, '#show-collections')
  await create(panel, 'API')
  await create(panel, 'Outer', 'API')
  await create(panel, 'Inner', 'Outer')
  await create(panel, 'Empty collection')
  await create(panel, 'Empty folder', 'API')
  await click(panel, '#close-collections')
  await fill(panel, '#request-url', `${api.origin}/echo`)
  await saveIn(panel, 'Keep until confirmed', '\u00a0\u00a0\u00a0\u00a0Inner')
  await saveIn(panel, 'Delete immediately', 'API')
  await click(panel, '#show-collections')
  await expect(row(panel, 'Delete immediately').getByRole('button', {name: 'Delete', exact: true})).toBeVisible()
  await row(panel, 'Delete immediately').getByRole('button', {name: 'Delete', exact: true}).click()
  await expect(row(panel, 'Delete immediately')).toHaveCount(0)
  await expectHidden(panel, '#collection-delete-warning')
  await proof(panel, 'request-deleted-without-confirmation')
  await row(panel, 'Outer').getByRole('button', {name: 'Delete', exact: true}).click()
  await expect(panel.locator('#collection-delete-warning')).toContainText('Outer')
  await proof(panel, 'folder-delete-confirmation')
  await click(panel, '#cancel-collection-delete')
  await expect(row(panel, 'Keep until confirmed')).toBeVisible()
  expect((await panel.evaluate(storedCollections)).collections.find(c => c.name === 'API').requests[0].requests[0].requests).toHaveLength(1)
  await proof(panel, 'cancel-folder-delete-keeps-contents')
  await row(panel, 'Outer').getByRole('button', {name: 'Delete', exact: true}).click()
  await click(panel, '#confirm-collection-delete')
  await expect(row(panel, 'Outer')).toHaveCount(0)
  await expect(row(panel, 'Keep until confirmed')).toHaveCount(0)
  expect((await panel.evaluate(storedCollections)).collections.find(c => c.name === 'API').requests.map(item => item.name)).toEqual(['Empty folder'])
  await row(panel, 'Empty folder').getByRole('button', {name: 'Delete', exact: true}).click()
  await expect(row(panel, 'Empty folder')).toHaveCount(0)
  await expectHidden(panel, '#collection-delete-warning')
  await row(panel, 'Empty collection').getByRole('button', {name: 'Delete', exact: true}).click()
  await expect(row(panel, 'Empty collection')).toHaveCount(0)
  await expectHidden(panel, '#collection-delete-warning')
  const remaining = await panel.evaluate(storedCollections)
  expect(remaining.index.map(c => c.name)).toEqual(['API'])
  expect(remaining.collections.map(c => c.name)).toEqual(['API'])
  expect(remaining.collections[0].requests).toEqual([])
  await proof(panel, 'recursive-delete-and-empty-collection-removed')
})

test('deleting the displayed request keeps all editor values and makes Save open Save as', async ({extension, api}) => {
  const panel = await extension.openPanel()
  await fill(panel, '#request-url', `${api.origin}/echo?kept=yes`)
  await panel.locator('#request-method').selectOption('POST')
  await click(panel, '#body-tab')
  await fill(panel, '#request-body', '{"keep":true}')
  await click(panel, '#save-as')
  await fill(panel, '#save-request-name', 'Displayed request')
  await fill(panel, '#new-collection-name', 'API')
  await click(panel, '#confirm-save-as')
  await expectHidden(panel, '#save-as-dialog')
  const before = await savedWorkspaceWith(panel, 'name', 'Displayed request')
  await click(panel, '#show-collections')
  await expect(row(panel, 'Displayed request').getByRole('button', {name: 'Delete', exact: true})).toBeVisible()
  await row(panel, 'Displayed request').getByRole('button', {name: 'Delete', exact: true}).click()
  await expect(row(panel, 'Displayed request')).toHaveCount(0)
  await click(panel, '#close-collections')
  await expectValue(panel, '#request-url', `${api.origin}/echo?kept=yes`)
  await expectValue(panel, '#request-method', 'POST')
  await expectValue(panel, '#request-body', '{"keep":true}')
  await expectText(panel, '#request-name', 'Displayed request')
  expect((await panel.evaluate(storedWorkspace)).draft.editor).toEqual(before.draft.editor)
  await proof(panel, 'deleted-request-editor-values-kept')
  await click(panel, '#save-request')
  await expect(panel.locator('#save-as-dialog')).toBeVisible()
  await expectValue(panel, '#save-request-name', 'Displayed request')
  await proof(panel, 'deleted-request-save-opens-save-as')
})

